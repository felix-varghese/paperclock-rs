# Confines the Rust/ESP toolchain and build output to this project folder.
# Requires Windows NTFS long-path support enabled (see below).
# Dot-source this before any cargo/rustup/espup/espflash command:
#   . .\env.ps1

$ProjectRoot = $PSScriptRoot

# rustup/cargo need RUSTUP_HOME/CARGO_HOME set explicitly - redirecting
# HOME/USERPROFILE alone isn't enough.
$env:USERPROFILE = "$ProjectRoot\.toolchain\home"
$env:HOME        = "$ProjectRoot\.toolchain\home"
$env:RUSTUP_HOME = "$ProjectRoot\.toolchain\rustup"
$env:CARGO_HOME  = "$ProjectRoot\.toolchain\cargo"

New-Item -ItemType Directory -Force -Path $env:USERPROFILE, $env:RUSTUP_HOME, $env:CARGO_HOME | Out-Null

# Confined Python (system Python was 3.8, too old for ESP-IDF v5.5's 3.9+ requirement)
$env:PATH = "$ProjectRoot\.toolchain\python;$env:CARGO_HOME\bin;$env:PATH"

# Generated by `espup install`; sets LIBCLANG_PATH, xtensa gcc PATH, etc.
$ExportEsp = "$ProjectRoot\.toolchain\export-esp.ps1"
if (Test-Path $ExportEsp) { . $ExportEsp }

# Build output and the ESP-IDF checkout, kept out of firmware/ so a clean
# clone stays small. Everything the build actually needs to be correct
# lives in firmware/.cargo/config.toml instead, so `cargo build` works
# without this script for anyone who already has espup set up.
$BuildRoot = "$ProjectRoot\.build"
$env:CARGO_TARGET_DIR = $BuildRoot
$env:ESP_IDF_TOOLS_INSTALL_DIR = "custom:$BuildRoot\.embuild"
